/**
 * Returns unambiguous, natural pronunciation for a kanji card/modal.
 * Example: for 四 returns 'よん', for 七 returns 'なな', for 水 returns 'みず'.
 */
export function getKanjiPronunciation(kanji: string | {
  char?: string;
  kanji?: string;
  onyomi?: string[] | string;
  kunyomi?: string[] | string;
}): string {
  const char = typeof kanji === 'string' ? kanji : (kanji.char || (kanji as any).kanji || '');
  
  // 1. Curated primary natural pronunciation
  if (MOST_USED_KANJI_PRONUNCIATION[char]) {
    return MOST_USED_KANJI_PRONUNCIATION[char];
  }

  // 2. Kunyomi first (natural standalone noun/verb reading)
  if (typeof kanji !== 'string') {
    const kun = Array.isArray(kanji.kunyomi) 
      ? kanji.kunyomi[0] 
      : (kanji.kunyomi ? kanji.kunyomi.split(/[,、\s]+/)[0] : undefined);
    if (kun) {
      const kana = romajiToHiragana(kun);
      if (kana) return kana;
    }

    // 3. Onyomi fallback
    const on = Array.isArray(kanji.onyomi) 
      ? kanji.onyomi[0] 
      : (kanji.onyomi ? kanji.onyomi.split(/[,、\s]+/)[0] : undefined);
    if (on) {
      const kana = romajiToHiragana(on);
      if (kana) return kana;
    }
  }

  return char;
}
