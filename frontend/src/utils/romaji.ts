export function romajiToHiragana(str: string): string {
  if (!str) return '';
  // Check if string already contains Japanese characters
  if (/[\u3040-\u309F\u30A0-\u30FF]/.test(str)) {
    return str;
  }

  let s = str.toLowerCase().replace(/[^a-z]/g, '');
  let result = '';
  let i = 0;
  while (i < s.length) {
    // Double consonant check (e.g. tt -> っ)
    if (i + 1 < s.length && s[i] === s[i + 1] && !'aeioun'.includes(s[i])) {
      result += 'っ';
      i++;
      continue;
    }
    // 3-char match
    if (i + 3 <= s.length && ROMAJI_TO_HIRAGANA_MAP[s.slice(i, i + 3)]) {
      result += ROMAJI_TO_HIRAGANA_MAP[s.slice(i, i + 3)];
      i += 3;
      continue;
    }
    // 2-char match
    if (i + 2 <= s.length && ROMAJI_TO_HIRAGANA_MAP[s.slice(i, i + 2)]) {
      result += ROMAJI_TO_HIRAGANA_MAP[s.slice(i, i + 2)];
      i += 2;
      continue;
    }
    // 1-char match
    if (ROMAJI_TO_HIRAGANA_MAP[s[i]]) {
      result += ROMAJI_TO_HIRAGANA_MAP[s[i]];
      i++;
      continue;
    }
    result += s[i];
    i++;
  }
  return result;
}

